#!/usr/bin/env python3
"""Generates widgets/pokemon.c: the 151 Gen 1 Pokemon as 1-bit nice!view images.

Usage: gen_pokemon.py <sprites_dir> <names.json> <out.c> [preview.png]
  sprites_dir: PokeAPI gen-i red-blue sprites named 1.png .. 151.png
  names.json:  list with the 151 names in Pokedex order
"""
import json
import sys
from PIL import Image, ImageDraw, ImageFont, ImageOps

W, H = 68, 140  # upright (portrait) layout; the panel data is this rotated 90 deg CCW
SPRITE = 66


def render(path, num, name):
    sp = Image.open(path).convert("RGBA")
    sp = sp.crop(sp.getchannel("A").getbbox())
    bg = Image.new("RGBA", sp.size, "white")
    bg.alpha_composite(sp)
    g = ImageOps.autocontrast(bg.convert("L"), cutoff=1)
    scale = min(SPRITE / g.width, SPRITE / g.height)
    g = g.resize((max(1, round(g.width * scale)), max(1, round(g.height * scale))), Image.LANCZOS)
    page = Image.new("L", (W, H), 255)
    page.paste(g, ((W - g.width) // 2, 6 + (SPRITE - g.height)))
    bw = page.convert("1")  # Floyd-Steinberg dither
    d = ImageDraw.Draw(bw)
    d.fontmode = "1"
    for text, y in ((name.upper(), 86), (f"#{num:03d}", 104)):
        size = 11
        font = ImageFont.load_default(size=size)
        while d.textlength(text, font=font) > W - 2:
            size -= 1
            font = ImageFont.load_default(size=size)
        w = d.textlength(text, font=font)
        d.text(((W - w) / 2, y), text, font=font, fill=0)
    return bw


def pack(img):
    data = img.rotate(90, expand=True)  # 140x68
    assert data.size == (140, 68)
    out = bytearray()
    for y in range(68):
        for bx in range(18):
            b = 0
            for i in range(8):
                x = bx * 8 + i
                b = (b << 1) | (1 if x < 140 and data.getpixel((x, y)) else 0)
            out.append(b)
    return bytes(out)


def main():
    sprites, names_path, out_path = sys.argv[1:4]
    names = json.load(open(names_path))
    assert len(names) == 151
    imgs = [render(f"{sprites}/{n}.png", n, names[n - 1]) for n in range(1, 152)]
    if len(sys.argv) > 4:
        sheet = Image.new("1", (W * 16, H * 10), 1)
        for i, im in enumerate(imgs[:160]):
            sheet.paste(im, ((i % 16) * W, (i // 16) * H))
        sheet.save(sys.argv[4])
    o = [
        "/*",
        " * Generated by scripts/gen_pokemon.py - Gen 1 Pokemon art (sprites from PokeAPI/sprites).",
        " * Image: 140x68, 1bpp, rotated like the other nice!view art.",
        " */",
        "",
        "#include <lvgl.h>",
        "",
        "#ifndef LV_ATTRIBUTE_MEM_ALIGN",
        "#define LV_ATTRIBUTE_MEM_ALIGN",
        "#endif",
        "",
    ]
    for n, im in enumerate(imgs, 1):
        raw = pack(im)
        o.append(f"static const LV_ATTRIBUTE_MEM_ALIGN LV_ATTRIBUTE_LARGE_CONST uint8_t pokemon_{n}_map[] = {{")
        o += [
            "#if CONFIG_NICE_VIEW_WIDGET_INVERTED",
            "    0xff, 0xff, 0xff, 0xff, 0x00, 0x00, 0x00, 0xff,",
            "#else",
            "    0x00, 0x00, 0x00, 0xff, 0xff, 0xff, 0xff, 0xff,",
            "#endif",
        ]
        for i in range(0, len(raw), 18):
            o.append("    " + ", ".join(f"0x{b:02x}" for b in raw[i : i + 18]) + ",")
        o.append("};\n")
    o.append("const lv_img_dsc_t pokemon_imgs[151] = {")
    for n in range(1, 152):
        o.append(f"    {{.header.cf = LV_COLOR_FORMAT_I1, .header.w = 140, .header.h = 68, "
                 f".data_size = {8 + 18 * 68}, .data = pokemon_{n}_map}},")
    o.append("};\n")
    open(out_path, "w").write("\n".join(o))


main()
